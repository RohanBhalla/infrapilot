def _skip(*checks: tuple[str, str]) -> list[str]:
    """CloudFormation Metadata that tells checkov which rules we skip, and why."""
    lines = ["    Metadata:", "      checkov:", "        skip:"]
    for check_id, why in checks:
        lines += [f"          - id: {check_id}", f"            comment: {_scalar(why)}"]
    return lines


def _template(spa: bool, domain: str | None, ci: bool) -> str:
    out = [
        f"# Generated by InfraPilot: static site on S3 + CloudFront{' (single-page app)' if spa else ''}.",
        'AWSTemplateFormatVersion: "2010-09-09"',
        "Description: Static website on a private S3 bucket served by CloudFront over HTTPS",
        "",
        "Parameters:",
    ]
    if domain:
        out += [
            "  DomainName:",
            "    Type: String",
            f"    Default: {domain}",
            "    Description: Your site's domain; point it at the CloudFront URL in your DNS",
            "  CertificateArn:",
            "    Type: String",
            "    AllowedPattern: arn:aws:acm:us-east-1:\\d{12}:certificate/.+",
            "    Description: ACM certificate for the domain; CloudFront needs it in us-east-1",
        ]
    if ci:
        out += [
            "  GitHubRepository:",
            "    Type: String",
            '    Default: ""',
            "    AllowedPattern: ^$|^[\\w.-]+/[\\w.-]+$",
            "    Description: owner/repo allowed to deploy (creates a GitHub OIDC deploy role); empty for none",
            "",
            "Conditions:",
            "  HasGitHubRepository: !Not [!Equals [!Ref GitHubRepository, \"\"]]",
        ]
    if not domain and not ci:
        del out[-2:]  # no parameters

    out += ["", "Resources:", "  SiteBucket:", "    Type: AWS::S3::Bucket"]
    out += _skip(("CKV_AWS_18", "Access logs need a second bucket and cost extra; CloudFront metrics are "
                                "enough for a small site. Add logging if you need an audit trail."))
    out += [
        "    Properties:",
        "      BucketEncryption:",
        "        ServerSideEncryptionConfiguration:",
        "          - ServerSideEncryptionByDefault:",
        "              SSEAlgorithm: AES256",
        "      PublicAccessBlockConfiguration:",
        "        BlockPublicAcls: true",
        "        BlockPublicPolicy: true",
        "        IgnorePublicAcls: true",
        "        RestrictPublicBuckets: true",
        "      OwnershipControls:",
        "        Rules:",
        "          - ObjectOwnership: BucketOwnerEnforced",
        "      VersioningConfiguration:",
        "        Status: Enabled  # roll back a bad upload; old versions are deleted after 30 days",
        "      LifecycleConfiguration:",
        "        Rules:",
        "          - Id: expire-old-versions",
        "            Status: Enabled",
        "            NoncurrentVersionExpiration:",
        "              NoncurrentDays: 30",
        "            AbortIncompleteMultipartUpload:",
        "              DaysAfterInitiation: 1",
        "",
        "  SiteBucketPolicy:",
        "    Type: AWS::S3::BucketPolicy",
        "    Properties:",
        "      Bucket: !Ref SiteBucket",
        "      PolicyDocument:",
        '        Version: "2012-10-17"',
        "        Statement:",
        "          - Sid: CloudFrontReadsTheSite",
        "            Effect: Allow",
        "            Principal:",
        "              Service: cloudfront.amazonaws.com",
        "            Action: s3:GetObject",
        "            Resource: !Sub ${SiteBucket.Arn}/*",
        "            Condition:",
        "              StringEquals:",
        "                AWS:SourceArn: !Sub arn:${AWS::Partition}:cloudfront::${AWS::AccountId}:distribution/${Distribution}",
        "          - Sid: HttpsOnly",
        "            Effect: Deny",
        "            Principal: \"*\"",
        "            Action: s3:*",
        "            Resource:",
        "              - !GetAtt SiteBucket.Arn",
        "              - !Sub ${SiteBucket.Arn}/*",
        "            Condition:",
        "              Bool:",
        "                aws:SecureTransport: false",
        "",
        "  OriginAccessControl:",
        "    Type: AWS::CloudFront::OriginAccessControl",
        "    Properties:",
        "      OriginAccessControlConfig:",
        "        Name: !Sub ${AWS::StackName}-oac",
        "        OriginAccessControlOriginType: s3",
        "        SigningBehavior: always",
        "        SigningProtocol: sigv4",
        "",
        "  Distribution:",
        "    Type: AWS::CloudFront::Distribution",
    ]
    skips = [
        ("CKV_AWS_68", "AWS WAF costs at least $5/month plus per-request fees; add it if the site needs "
                       "bot or rate protection."),
        ("CKV_AWS_86", "CloudFront access logs need a log bucket and cost extra; enable them if you need "
                       "per-request logs."),
    ]
    if not domain:
        skips.append(("CKV_AWS_174", "The default *.cloudfront.net certificate can't set a minimum TLS "
                                     "version; with your own domain the template uses TLS 1.2."))
    out += _skip(*skips)
    out += [
        "    Properties:",
        "      DistributionConfig:",
        "        Enabled: true",
        "        Comment: !Sub ${AWS::StackName} static site",
        "        DefaultRootObject: index.html",
        "        HttpVersion: http2and3",
        "        IPV6Enabled: true",
        "        PriceClass: PriceClass_100  # North America and Europe edges only: the cheapest",
    ]
    if domain:
        out += [
            "        Aliases:",
            "          - !Ref DomainName",
            "        ViewerCertificate:",
            "          AcmCertificateArn: !Ref CertificateArn",
            "          MinimumProtocolVersion: TLSv1.2_2021",
            "          SslSupportMethod: sni-only",
        ]
    out += [
        "        Origins:",
        "          - Id: site",
        "            DomainName: !GetAtt SiteBucket.RegionalDomainName",
        "            OriginAccessControlId: !GetAtt OriginAccessControl.Id",
        "            S3OriginConfig:",
        '              OriginAccessIdentity: ""',
        "        DefaultCacheBehavior:",
        "          TargetOriginId: site",
        "          ViewerProtocolPolicy: redirect-to-https",
        "          AllowedMethods: [GET, HEAD]",
        "          Compress: true",
        f"          CachePolicyId: {CACHING_OPTIMIZED}  # AWS managed: CachingOptimized",
        f"          ResponseHeadersPolicyId: {SECURITY_HEADERS}  # AWS managed: SecurityHeadersPolicy",
    ]
    if spa:
        out += ["        # Single-page app: paths that aren't files (/about, /users/1) load index.html.",
                "        CustomErrorResponses:"]
        for code in (403, 404):  # S3 answers 403 for missing files when CloudFront can't list the bucket
            out += [f"          - ErrorCode: {code}", "            ResponseCode: 200",
                    "            ResponsePagePath: /index.html", "            ErrorCachingMinTTL: 10"]

    if ci:
        out += [
            "",
            "  # Lets the GitHub Actions workflow deploy this site, and nothing else. It trusts only the",
            "  # repo's `production` environment. Needs the GitHub OIDC provider in this account (once).",
            "  GitHubDeployRole:",
            "    Type: AWS::IAM::Role",
            "    Condition: HasGitHubRepository",
            "    Properties:",
            "      AssumeRolePolicyDocument:",
            '        Version: "2012-10-17"',
            "        Statement:",
            "          - Effect: Allow",
            "            Principal:",
            "              Federated: !Sub arn:${AWS::Partition}:iam::${AWS::AccountId}:oidc-provider/token.actions.githubusercontent.com",
            "            Action: sts:AssumeRoleWithWebIdentity",
            "            Condition:",
            "              StringEquals:",
            "                token.actions.githubusercontent.com:aud: sts.amazonaws.com",
            "                token.actions.githubusercontent.com:sub: !Sub repo:${GitHubRepository}:environment:production",
            "      Policies:",
            "        - PolicyName: deploy-site",
            "          PolicyDocument:",
            '            Version: "2012-10-17"',
            "            Statement:",
            "              - Effect: Allow",
            "                Action: s3:ListBucket",
            "                Resource: !GetAtt SiteBucket.Arn",
            "              - Effect: Allow",
            "                Action: [s3:PutObject, s3:DeleteObject]",
            "                Resource: !Sub ${SiteBucket.Arn}/*",
            "              - Effect: Allow",
            "                Action: cloudfront:CreateInvalidation",
            "                Resource: !Sub arn:${AWS::Partition}:cloudfront::${AWS::AccountId}:distribution/${Distribution}",
            "              - Effect: Allow",
            "                Action: cloudformation:DescribeStacks",
            "                Resource: !Ref AWS::StackId",
        ]

    out += [
        "",
        "Outputs:",
        "  SiteUrl:",
        "    Value: " + ("!Sub https://${DomainName}" if domain else "!Sub https://${Distribution.DomainName}"),
        "  CloudFrontUrl:",
        *(["    Description: Point your domain's DNS record here"] if domain else []),
        "    Value: !GetAtt Distribution.DomainName",
        "  BucketName:",
        "    Value: !Ref SiteBucket",
        "  DistributionId:",
        "    Value: !Ref Distribution",
    ]
    if ci:
        out += ["  DeployRoleArn:", "    Condition: HasGitHubRepository",
                "    Description: Save as the repository secret AWS_ROLE_ARN",
                "    Value: !GetAtt GitHubDeployRole.Arn"]
    return "\n".join(out) + "\n"


def _workflow(site_dir: str, framework: str, region: str, node: str | None, v: dict) -> str:
    steps = [step("Check out the code", uses=pins.pin("actions/checkout", v))]
    if framework in BUILT:
        steps += [
            step("Set up Node.js", uses=pins.pin("actions/setup-node", v),
                 with_={"node-version": node or "lts/*", "cache": "npm"}),
            step("Install dependencies", run="npm ci"),
            step("Build the site", run="npm run build"),
        ]
    steps += [
        _aws_login(v),
        step("Find the bucket and distribution", id="site", run="\n".join([
            'aws cloudformation describe-stacks --stack-name "$STACK_NAME" \\',
            '  --query "Stacks[0].Outputs" --output json > outputs.json',
            'for key in BucketName DistributionId; do',
            '  echo "$key=$(jq -r --arg k "$key" \'.[] | select(.OutputKey == $k) | .OutputValue\' outputs.json)" '
            '>> "$GITHUB_OUTPUT"',
            'done'])),
        step("Upload the site", env={"BUCKET": "${{ steps.site.outputs.BucketName }}"},
             run='aws s3 sync "$SITE_DIR" "s3://$BUCKET" --delete'),
        step("Clear the CloudFront cache", env={"DISTRIBUTION": "${{ steps.site.outputs.DistributionId }}"},
             run='aws cloudfront create-invalidation --distribution-id "$DISTRIBUTION" --paths "/*"'),
    ]
    return "\n".join([
        "# Generated by InfraPilot: builds the site and uploads it to the static-site stack on each push.",
        "name: Deploy site",
        "",
        "on:",
        "  push:",
        "    branches: [main]",
        "  workflow_dispatch:  # also lets you run it by hand from the Actions tab",
        "",
        "permissions:",
        "  contents: read",
        "",
        "# One deploy at a time; a newer push waits instead of cancelling an upload halfway.",
        "concurrency:",
        "  group: deploy-site",
        "  cancel-in-progress: false",
        "",
        "env:",
        f"  AWS_REGION: {region}",
        f"  STACK_NAME: {STACK}",
        f"  SITE_DIR: {_scalar(site_dir)}  # folder with the built site",
        "",
        "jobs:",
        "  deploy:",
        "    runs-on: ubuntu-latest",
        "    timeout-minutes: 15",
        "    environment: production",
        "    permissions:",
        "      contents: read",
        "      id-token: write  # lets the job sign in to AWS with OIDC (no stored AWS keys)",
        "    steps:",
        "\n".join(_indent(s, 6) for s in steps),
    ]) + "\n"


def _is_yes(value) -> bool:
    return value is True or str(value).lower() in ("true", "yes", "1")


def generate(params: dict, versions: dict | None = None) -> Plan:
    v = versions or {}
    notes: list[str] = []

    site_dir = str(params.get("source_dir") or "dist").strip().strip("/").removeprefix("./") or "dist"
    if not SITE_DIR.fullmatch(site_dir) or ".." in site_dir.split("/"):
        notes.append(f"`{params.get('source_dir')}` doesn't look like a folder path, so I used `dist`.")
        site_dir = "dist"
    framework = params.get("framework") or "plain"
    spa = _is_yes(params.get("spa_routing"))
    ci = _is_yes(params.get("ci_deploy"))
    region = str(params.get("region") or "us-east-1").strip()
    if not re.fullmatch(r"[a-z]{2}(-gov)?-[a-z]+-\d", region):
        notes.append(f"`{region}` isn't an AWS region name, so I used us-east-1.")
        region = "us-east-1"

    raw_domain = str(params.get("custom_domain") or "").strip().lower().removeprefix("https://").rstrip("/")
    domain = raw_domain if DOMAIN.fullmatch(raw_domain) else None
    if raw_domain and not domain and not raw_domain.startswith("none") and raw_domain not in ("no", "false"):
        notes.append(f"`{params.get('custom_domain')}` isn't a domain name, so the site uses its CloudFront URL.")

    node = None
    if ci and framework in BUILT:
        lts = (v.get("nodejs") or {}).get("lts")
        node = lts.split(".")[0] if lts else None
        if framework == "other":
            notes.append("I assumed the site builds with `npm run build`; change the build steps if it doesn't.")
        if framework == "angular":
            notes.append(f"Angular usually builds to `dist/<project>/browser`; check that `{site_dir}` is the "
                         "folder with index.html.")

    files = [PlanFile(path=TEMPLATE_PATH, content=_template(spa, domain, ci))]
    if ci:
        files.append(PlanFile(path=WORKFLOW_PATH, content=_workflow(site_dir, framework, region, node, v)))

    params_flag = []
    if domain:
        params_flag.append(f"DomainName={domain} CertificateArn=<your certificate ARN>")
    if ci:
        params_flag.append("GitHubRepository=<owner/repo>")
    deploy_cmd = (f"aws cloudformation deploy --template-file {TEMPLATE_PATH} --stack-name {STACK} "
                  f"--region {region} --capabilities CAPABILITY_IAM"
                  + (f" --parameter-overrides {' '.join(params_flag)}" if params_flag else ""))
    setup = []
    if domain:
        setup.append(f"An ACM certificate for `{domain}` in **us-east-1** (CloudFront only uses certificates "
                     "from that region), validated by DNS.")
    if ci:
        setup.append("The GitHub OIDC identity provider in your AWS account (once per account): "
                     "`token.actions.githubusercontent.com` with audience `sts.amazonaws.com`.")
    setup.append(f"Create the stack: `{deploy_cmd}`")
    if ci:
        setup.append("Save the stack's `DeployRoleArn` output as the repository secret `AWS_ROLE_ARN`, and "
                     "create a `production` environment in the repo settings. Then push to main.")
    else:
        setup.append(f"Upload the site: `aws s3 sync {site_dir} s3://<BucketName output> --delete`, then "
                     "`aws cloudfront create-invalidation --distribution-id <DistributionId output> --paths \"/*\"`.")
    if domain:
        setup.append(f"Point `{domain}` at the `CloudFrontUrl` output (a CNAME, or an alias record in Route 53).")
    if region != "us-east-1":
        notes.append(f"The bucket is created in {region}; CloudFront serves it worldwide either way.")
    notes.append("Deleting the stack fails while the bucket has files: empty it first "
                 "(`aws s3 rm s3://<bucket> --recursive`, plus old versions in the console).")

    docs = DOCS + (SPA_DOCS if spa else []) + (DOMAIN_DOCS if domain else []) + (OIDC_DOCS if ci else [])
    used = sorted({a for f in files for a, _ in pins.USES.findall(f.content)})
    plan = Plan(
        intent="deploy_static_site", params=params, files=files,
        summary=_summary(site_dir, spa, domain, ci),
        setup=setup, notes=notes,
        citations=docs + [Source(title=f"{a} releases", url=pins.source_url(a, v)) for a in used],
        estimated_cost_note="A few cents a month for a small site: S3 storage is about $0.023/GB-month, and "
                            "CloudFront's free tier covers 1 TB of transfer and 10 million requests a month.",
    )
    workflows = "\n".join(f.content for f in files if f.path == WORKFLOW_PATH)
    plan.validations = ([pins.check_pins(workflows, v)] if workflows else []) + validate.run(files)
    return plan


def _summary(site_dir, spa, domain, ci) -> str:
    parts = [f"A CloudFormation template (`{TEMPLATE_PATH}`) that hosts `{site_dir}/` on a private S3 bucket "
             "behind CloudFront, with HTTPS and security headers"
             + (f", served at {domain}" if domain else "") + "."]
    if spa:
        parts.append("Unknown paths load index.html, so your app's router handles them.")
    if ci:
        parts.append(f"A GitHub Actions workflow (`{WORKFLOW_PATH}`) builds the site and uploads it on every "
                     "push to main, signing in to AWS with a role the template creates.")
    return " ".join(parts)
