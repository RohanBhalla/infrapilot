def _dockerignore(language: str) -> str:
    return "\n".join([
        "# Generated by InfraPilot: files the image doesn't need (smaller, faster builds; no secrets).",
        ".git", ".github", ".env", ".env.*", "*.log", "Dockerfile", ".dockerignore", "infra",
        *IGNORE[language],
    ]) + "\n"


