def generate(params: dict, versions: dict | None = None) -> Plan | None:
    v = versions or {}
    language = params.get("language")
    if language not in LANGUAGES:
        return None  # "other": the chat says file generation isn't available for it yet
    notes: list[str] = []

    try:
        port = int(params.get("app_port"))
    except (TypeError, ValueError):
        port = 0
    if not 1 <= port <= 65535:
        notes.append(f"`{params.get('app_port')}` isn't a port number, so I used 8080.")
        port = 8080
    defaults = {"node": "npm start", "python": "python main.py", "java": "java -jar app.jar", "go": "./app"}
    start = str(params.get("start_command") or defaults[language]).strip() or defaults[language]
    version = _versions(v)[language]
    ecs = _is_yes(params.get("deploy_to_ecs"))
    push = _is_yes(params.get("push_to_ecr", True)) or ecs
    if ecs and not _is_yes(params.get("push_to_ecr", True)):
        notes.append("ECS needs the image in ECR, so the workflow pushes it there too.")
    region = str(params.get("region") or "us-east-1").strip()
    if not re.fullmatch(r"[a-z]{2}(-gov)?-[a-z]+-\d", region):
        notes.append(f"`{region}` isn't an AWS region name, so I used us-east-1.")
        region = "us-east-1"

    files = [PlanFile(path=DOCKERFILE_PATH, content=_dockerfile(language, port, start, version), language="dockerfile"),
             PlanFile(path=IGNORE_PATH, content=_dockerignore(language), language="text")]
    if push:
        files += [PlanFile(path=TEMPLATE_PATH, content=_template(language, port, ecs, ci=True)),
                  PlanFile(path=WORKFLOW_PATH, content=_workflow(ecs, region, v))]

    image = "my-app"
    setup = []
    if push:
        setup += ["The GitHub OIDC identity provider in your AWS account (once per account): "
                  "`token.actions.githubusercontent.com` with audience `sts.amazonaws.com`.",
                  f"Create the stack: `aws cloudformation deploy --template-file {TEMPLATE_PATH} --stack-name {STACK} "
                  f"--region {region} --capabilities CAPABILITY_IAM --parameter-overrides "
                  "GitHubRepository=<owner/repo>`." + (" The service starts with no tasks." if ecs else ""),
                  "Save the stack's `DeployRoleArn` output as the repository secret `AWS_ROLE_ARN`, and create a "
                  "`production` environment in the repo settings. Then push to main"
                  + (" to build the image and start the service." if ecs else " to build and push the image.")]
    setup.append(f"Try it locally: `docker build -t {image} . && docker run --rm -p {port}:{port} {image}`, then "
                 f"open http://localhost:{port}.")

    notes.append(f"Your app must listen on `0.0.0.0` (not `localhost`) port {port}, or it can't be reached from "
                 "outside the container.")
    notes += {
        "node": ["The image installs from `package-lock.json` with `npm ci`; commit the lock file."],
        "python": ["Dependencies come from `requirements.txt`. For a web app, start it with a server such as "
                   f"`uvicorn main:app --host 0.0.0.0 --port {port}` or `gunicorn`."],
        "java": ["The build uses Maven (`pom.xml`) and copies the jar from `target/`. For Gradle, change the build "
                 "stage to `./gradlew bootJar` and `build/libs/`."],
        "go": [f"The binary is built from the repo root and started as `/app`"
               + ("" if start == "./app" else f"; I didn't use `{start}`") + "."],
    }[language]
    if ecs:
        notes.append("There's no load balancer, so the app is reached at the task's public IP (ECS console → the "
                     f"service → Tasks → Public IP, port {port}). It changes on every deploy; add an Application "
                     "Load Balancer (about $16/month) for a fixed address and HTTPS.")
        notes.append("Deleting the stack removes the service, the network and the repository with its images.")

    docs = DOCS + (ECR_DOCS + OIDC_DOCS if push else []) + (ECS_DOCS if ecs else [])
    used = sorted({a for f in files for a, _ in pins.USES.findall(f.content)})
    plan = Plan(
        intent="containerize", params=params, files=files,
        summary=_summary(language, port, push, ecs),
        setup=setup, notes=notes,
        citations=docs + [Source(title=f"{a} releases", url=pins.source_url(a, v)) for a in used],
        estimated_cost_note=_cost(push, ecs),
    )
    workflows = "\n".join(f.content for f in files if f.path == WORKFLOW_PATH)
    plan.validations = ([pins.check_pins(workflows, v)] if workflows else []) + validate.run(files)
    return plan


def _cost(push: bool, ecs: bool) -> str | None:
    if ecs:
        return ("About $11/month while the service runs: Fargate on arm64 at 0.25 vCPU and 0.5 GB is about "
                "$7/month and its public IPv4 address $3.65/month. ECR storage is $0.10/GB-month. Set the desired "
                "count to 0 or delete the stack to stop paying.")
    if push:
        return "ECR storage is $0.10/GB-month; the repository keeps the 10 newest images, usually well under $1/month."
    return None


def _summary(language: str, port: int, push: bool, ecs: bool) -> str:
    parts = [f"A two-stage `{DOCKERFILE_PATH}` for your {language} app on port {port} that runs as a normal user "
             f"and checks the port is answering, plus a `{IGNORE_PATH}`."]
    if push:
        parts.append(f"A CloudFormation template (`{TEMPLATE_PATH}`) with a private ECR repository"
                     + (" and an ECS Fargate service on arm64" if ecs else "")
                     + f", and a GitHub Actions workflow (`{WORKFLOW_PATH}`) that builds the image for arm64 and "
                     + ("pushes it, then rolls it out" if ecs else "pushes it") + " on every push to main.")
    return " ".join(parts)
