def _versions(v: dict) -> dict[str, str]:
    return {"node": _node_lts({}, v) or "24", "python": _newest_lambda(v, "python") or "3.14",
            "java": _newest_lambda(v, "java") or "25", "go": FALLBACK_GO}


def health_command(language: str, port: int) -> list[str] | None:
    """A check that the app accepts connections on its port (works for any app, unlike GET /).
    None for Go: the distroless image has no shell or tools to run one."""
    return {
        "node": ["node", "-e", f"require('net').connect({port}, '127.0.0.1')"
                               ".on('connect', () => process.exit(0)).on('error', () => process.exit(1))"],
        "python": ["python", "-c", f"import socket; socket.create_connection(('127.0.0.1', {port}), timeout=2)"],
        "java": ["bash", "-c", f"</dev/tcp/127.0.0.1/{port}"],
    }.get(language)


def _cmd(start: str) -> str:
    """Exec form, so the app gets stop signals directly; through sh -c when it uses shell syntax."""
    args = ["sh", "-c", start] if SHELL_SYNTAX.search(start) else shlex.split(start)
    return "CMD " + json.dumps(args)


def _dockerfile(language: str, port: int, start: str, version: str) -> str:
    out = ["# syntax=docker/dockerfile:1",
           f"# Generated by InfraPilot: {language} app on port {port}, built in two stages.", ""]
    if language == "node":
        image = f"{MIRROR}/node:{version}-slim"
        out += [
            f"FROM {image} AS build",
            "WORKDIR /app",
            "COPY package*.json ./",
            "RUN npm ci",
            "COPY . .",
            "# Build if the app has a build script (TypeScript, bundlers), then drop dev dependencies.",
            "RUN npm run build --if-present && npm prune --omit=dev",
            "",
            f"FROM {image}",
            "ENV NODE_ENV=production",
            "WORKDIR /app",
            "COPY --from=build /app ./",
            "# The image's `node` user.",
            "USER 1000:1000",
        ]
    elif language == "python":
        image = f"{MIRROR}/python:{version}-slim"
        out += [
            f"FROM {image} AS build",
            "WORKDIR /app",
            "COPY requirements.txt .",
            "RUN python -m venv /venv && /venv/bin/pip install --no-cache-dir -r requirements.txt",
            "",
            f"FROM {image}",
            'ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 PATH="/venv/bin:$PATH"',
            "WORKDIR /app",
            "COPY --from=build /venv /venv",
            "COPY . .",
            "RUN groupadd --system --gid 10001 app && useradd --system --uid 10001 --gid app app",
            "USER 10001:10001",
        ]
    elif language == "java":
        out += [
            "# The jar runs anywhere, so it's built on the build machine's own platform (no emulation).",
            f"FROM --platform=$BUILDPLATFORM {MIRROR}/maven:3.9-eclipse-temurin-{version} AS build",
            "WORKDIR /app",
            "COPY pom.xml .",
            "RUN mvn -B -ntp dependency:go-offline",
            "COPY src ./src",
            "RUN mvn -B -ntp package -DskipTests && cp target/*.jar app.jar",
            "",
            f"FROM {MIRROR}/eclipse-temurin:{version}-jre",
            "WORKDIR /app",
            "COPY --from=build /app/app.jar .",
            "RUN groupadd --system --gid 10001 app && useradd --system --uid 10001 --gid app app",
            "USER 10001:10001",
        ]
    else:  # go
        out += [
            "# Go cross-compiles, so the build runs on the build machine's own platform (no emulation).",
            f"FROM --platform=$BUILDPLATFORM {MIRROR}/golang:{version} AS build",
            "ARG TARGETOS TARGETARCH",
            "WORKDIR /src",
            "COPY go.mod go.sum* ./",
            "RUN go mod download",
            "COPY . .",
            'RUN CGO_ENABLED=0 GOOS=$TARGETOS GOARCH=$TARGETARCH go build -trimpath -ldflags="-s -w" -o /out/app .',
            "",
            "# Distroless: just the binary, no shell or package manager.",
            f"FROM {DISTROLESS}",
            "COPY --from=build /out/app /app",
            "# The image's `nonroot` user.",
            "USER 65532:65532",
        ]
    out.append(f"EXPOSE {port}")
    check = health_command(language, port)
    if check:
        out.append(f"HEALTHCHECK --interval=30s --timeout=3s --start-period=20s --retries=3 CMD {json.dumps(check)}")
    else:
        out.append("# checkov:skip=CKV_DOCKER_2: the distroless image has no shell to run a check; "
                   "ECS still replaces the task if the app exits")
    out.append('ENTRYPOINT ["/app"]' if language == "go" else _cmd(start))
    return "\n".join(out) + "\n"


