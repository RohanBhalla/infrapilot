"""Dockerfile generator (plan C10): a Dockerfile and .dockerignore for a Node, Python, Java or Go app,
plus, optionally, an ECR repository and an ECS Fargate service as a CloudFormation template and a
GitHub Actions workflow that builds the image and rolls it out on every push.

Deterministic, like the other generators. The Dockerfile builds in two stages so the final image
only has what's needed to run, starts from a current official image (mirrored on ECR Public, so CI
doesn't hit Docker Hub's pull limits), runs as a normal user and checks that the app's port answers.

The ECS service starts with 0 tasks, because there's no image yet. The workflow pushes an image tagged
with the commit and updates the stack's ImageTag parameter, which starts the task; CloudFormation
rolls back if the new version doesn't come up. There's no load balancer (about $16/month), so the
task is reached on its public IP.

Some checkov rules are skipped on purpose, with the reason written next to them: they add cost (KMS
keys, Container Insights) that a small service usually doesn't need, or (Go) can't apply.
"""

