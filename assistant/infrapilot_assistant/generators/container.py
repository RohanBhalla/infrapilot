def _role(name: str, service: str, statements: list[str], comment: str, condition: str | None = None) -> list[str]:
    out = ["", f"  # {comment}", f"  {name}:", "    Type: AWS::IAM::Role"]
    if condition:
        out.append(f"    Condition: {condition}")
    out += ["    Properties:", "      AssumeRolePolicyDocument:", '        Version: "2012-10-17"',
            "        Statement:", "          - Effect: Allow", "            Principal:",
            f"              Service: {service}", "            Action: sts:AssumeRole"]
    if statements:
        out += ["      Policies:", f"        - PolicyName: {name[0].lower() + name[1:]}", "          PolicyDocument:",
                '            Version: "2012-10-17"', "            Statement:", *statements]
    return out


def _allow(actions: list[str], resource: str) -> list[str]:
    action = actions[0] if len(actions) == 1 else "[" + ", ".join(actions) + "]"
    return ["              - Effect: Allow", f"                Action: {action}", f"                Resource: {resource}"]


PULL = ["ecr:BatchCheckLayerAvailability", "ecr:GetDownloadUrlForLayer", "ecr:BatchGetImage"]
PUSH = PULL + ["ecr:InitiateLayerUpload", "ecr:UploadLayerPart", "ecr:CompleteLayerUpload", "ecr:PutImage"]


def _template(language: str, port: int, ecs: bool, ci: bool) -> str:
    out = [
        f"# Generated by InfraPilot: an ECR repository{' and an ECS Fargate service' if ecs else ''} "
        f"for your {language} app.",
        'AWSTemplateFormatVersion: "2010-09-09"',
        "Description: " + ("ECR repository and ECS Fargate service for a container" if ecs
                           else "ECR repository for a container image"),
    ]
    params, conditions = [], []
    if ecs:
        params += ["  ImageTag:", "    Type: String", '    Default: ""', "    AllowedPattern: ^$|^[\\w.-]{1,128}$",
                   "    Description: Image tag to run; the workflow sets it. Empty runs no tasks (no image yet)"]
        conditions.append('  HasImage: !Not [!Equals [!Ref ImageTag, ""]]')
    if ci:
        params += ["  GitHubRepository:", "    Type: String", '    Default: ""',
                   "    AllowedPattern: ^$|^[\\w.-]+/[\\w.-]+$",
                   "    Description: owner/repo allowed to deploy (creates a GitHub OIDC deploy role); empty for none"]
        conditions.append('  HasGitHubRepository: !Not [!Equals [!Ref GitHubRepository, ""]]')
    if params:
        out += ["", "Parameters:", *params, "", "Conditions:", *conditions]

    out += ["", "Resources:", "  Repository:", "    Type: AWS::ECR::Repository"]
    out += _skip(("CKV_AWS_136", "A customer managed KMS key costs $1/month; ECR encrypts images with AES-256 "
                                 "by default."))
    lifecycle = {"rules": [{"rulePriority": 1, "description": "Keep the 10 newest images",
                            "selection": {"tagStatus": "any", "countType": "imageCountMoreThan", "countNumber": 10},
                            "action": {"type": "expire"}}]}
    out += [
        "    Properties:",
        "      ImageTagMutability: IMMUTABLE  # each commit gets its own tag; a tag never changes",
        "      ImageScanningConfiguration:",
        "        ScanOnPush: true  # basic scan for known vulnerabilities, free",
        "      EmptyOnDelete: true  # lets the stack delete the repository with its images",
        "      LifecyclePolicy:",
        f"        LifecyclePolicyText: {_scalar(json.dumps(lifecycle))}",
    ]
    if ecs:
        out += _ecs_resources(language, port)
    if ci:
        statements = (_allow(["ecr:GetAuthorizationToken"], '"*"  # ECR sign-in has no resource to scope to')
                      + _allow(PUSH, "!GetAtt Repository.Arn"))
        if ecs:
            statements += (
                _allow(["cloudformation:DescribeStacks", "cloudformation:DescribeStackEvents",
                        "cloudformation:UpdateStack"], "!Ref AWS::StackId")
                # What CloudFormation does with these credentials when only ImageTag changes.
                + _allow(["ecs:RegisterTaskDefinition", "ecs:DeregisterTaskDefinition", "ecs:DescribeTaskDefinition"],
                         '"*"  # task definition actions have no resource to scope to')
                + _allow(["ecs:UpdateService", "ecs:DescribeServices"], "!Ref Service")
                + _allow(["iam:PassRole"], "[!GetAtt TaskExecutionRole.Arn, !GetAtt TaskRole.Arn]"))
        else:
            statements += _allow(["cloudformation:DescribeStacks"], "!Ref AWS::StackId")
        out += [
            "",
            "  # Lets the GitHub Actions workflow push images" + (" and roll them out" if ecs else "")
            + ", and nothing else. It trusts",
            "  # only the repo's `production` environment. Needs the GitHub OIDC provider in this account (once).",
            "  GitHubDeployRole:",
            "    Type: AWS::IAM::Role",
            "    Condition: HasGitHubRepository",
        ]
        out += [
            "    Properties:",
            "      AssumeRolePolicyDocument:",
            '        Version: "2012-10-17"',
            "        Statement:",
            "          - Effect: Allow",
            "            Principal:",
            "              Federated: !Sub arn:${AWS::Partition}:iam::${AWS::AccountId}:oidc-provider/token.actions.githubusercontent.com",
            "            Action: sts:AssumeRoleWithWebIdentity",
            "            Condition:",
            "              StringEquals:",
            "                token.actions.githubusercontent.com:aud: sts.amazonaws.com",
            "                token.actions.githubusercontent.com:sub: !Sub repo:${GitHubRepository}:environment:production",
            "      Policies:",
            "        - PolicyName: deploy-container",
            "          PolicyDocument:",
            '            Version: "2012-10-17"',
            "            Statement:",
            *statements,
        ]

    out += ["", "Outputs:", "  RepositoryUri:", "    Value: !GetAtt Repository.RepositoryUri"]
    if ecs:
        out += ["  ClusterName:", "    Value: !Ref Cluster", "  ServiceName:", "    Value: !GetAtt Service.Name",
                "  LogGroup:", "    Value: !Ref LogGroup"]
    if ci:
        out += ["  DeployRoleArn:", "    Condition: HasGitHubRepository",
                "    Description: Save as the repository secret AWS_ROLE_ARN",
                "    Value: !GetAtt GitHubDeployRole.Arn"]
    return "\n".join(out) + "\n"


def _ecs_resources(language: str, port: int) -> list[str]:
    out = ["", "  # A small network of its own: two public subnets and no NAT gateway (that's about $32/month).",
           "  Vpc:", "    Type: AWS::EC2::VPC"]
    out += ["    Properties:", "      CidrBlock: 10.0.0.0/16", "      EnableDnsHostnames: true",
            "      EnableDnsSupport: true", "",
            "  InternetGateway:", "    Type: AWS::EC2::InternetGateway", "",
            "  GatewayAttachment:", "    Type: AWS::EC2::VPCGatewayAttachment", "    Properties:",
            "      VpcId: !Ref Vpc", "      InternetGatewayId: !Ref InternetGateway", "",
            "  PublicRouteTable:", "    Type: AWS::EC2::RouteTable", "    Properties:", "      VpcId: !Ref Vpc", "",
            "  PublicRoute:", "    Type: AWS::EC2::Route", "    DependsOn: GatewayAttachment", "    Properties:",
            "      RouteTableId: !Ref PublicRouteTable", "      DestinationCidrBlock: 0.0.0.0/0",
            "      GatewayId: !Ref InternetGateway"]
    for i, letter in enumerate("AB"):
        out += ["", f"  Subnet{letter}:", "    Type: AWS::EC2::Subnet", "    Properties:", "      VpcId: !Ref Vpc",
                f"      CidrBlock: 10.0.{i}.0/24", f'      AvailabilityZone: !Select [{i}, !GetAZs ""]',
                "      MapPublicIpOnLaunch: false  # the service asks for public IPs itself", "",
                f"  Subnet{letter}Routes:", "    Type: AWS::EC2::SubnetRouteTableAssociation", "    Properties:",
                f"      SubnetId: !Ref Subnet{letter}", "      RouteTableId: !Ref PublicRouteTable"]
    out += ["", "  ServiceSecurityGroup:", "    Type: AWS::EC2::SecurityGroup", "    Properties:",
            f"      GroupDescription: Lets anyone reach the app on port {port}", "      VpcId: !Ref Vpc",
            "      SecurityGroupIngress:", "        - IpProtocol: tcp", f"          FromPort: {port}",
            f"          ToPort: {port}", "          CidrIp: 0.0.0.0/0",
            f"          Description: The app's port, from anywhere",
            "      SecurityGroupEgress:", "        - IpProtocol: tcp", "          FromPort: 443", "          ToPort: 443",
            "          CidrIp: 0.0.0.0/0",
            "          Description: HTTPS out (pulling the image from ECR, sending logs, calling APIs)"]

    out += ["", "  Cluster:", "    Type: AWS::ECS::Cluster"]
    out += _skip(("CKV_AWS_65", "Container Insights is billed per metric; the service's basic CPU and memory "
                                "metrics are free. Turn it on if you need per-task metrics."))
    out += ["", "  LogGroup:", "    Type: AWS::Logs::LogGroup"]
    out += _skip(("CKV_AWS_158", "A customer managed KMS key costs $1/month; CloudWatch encrypts logs by "
                                 "default. Add KmsKeyId if your logs hold sensitive data."))
    out += ["    Properties:", "      RetentionInDays: 30"]

    out += _role("TaskExecutionRole", "ecs-tasks.amazonaws.com",
                 _allow(["ecr:GetAuthorizationToken"], '"*"  # ECR sign-in has no resource to scope to')
                 + _allow(PULL, "!GetAtt Repository.Arn")
                 + _allow(["logs:CreateLogStream", "logs:PutLogEvents"], "!GetAtt LogGroup.Arn"),
                 "What ECS needs to start the task: pull this repository's image and write its logs.")
    out += _role("TaskRole", "ecs-tasks.amazonaws.com", [],
                 "What your app may do in AWS: nothing yet. Add policies here (for example S3 or DynamoDB access).")

    check = health_command(language, port)
    out += ["", "  TaskDefinition:", "    Type: AWS::ECS::TaskDefinition"]
    out += [
        "    Properties:",
        "      Family: !Sub ${AWS::StackName}-app",
        '      Cpu: "256"  # 0.25 vCPU, the smallest size',
        '      Memory: "512"',
        "      NetworkMode: awsvpc",
        "      RequiresCompatibilities: [FARGATE]",
        "      RuntimePlatform:",
        "        CpuArchitecture: ARM64  # Graviton: about 20% cheaper than x86_64",
        "        OperatingSystemFamily: LINUX",
        "      ExecutionRoleArn: !GetAtt TaskExecutionRole.Arn",
        "      TaskRoleArn: !GetAtt TaskRole.Arn",
        "      ContainerDefinitions:",
        "        - Name: app",
        "          Image: !If [HasImage, !Sub \"${Repository.RepositoryUri}:${ImageTag}\", "
        "!Sub \"${Repository.RepositoryUri}:none\"]",
        "          Essential: true",
        "          PortMappings:",
        f"            - ContainerPort: {port}",
        "          LogConfiguration:",
        "            LogDriver: awslogs",
        "            Options:",
        "              awslogs-group: !Ref LogGroup",
        "              awslogs-region: !Ref AWS::Region",
        "              awslogs-stream-prefix: app",
    ]
    if check:
        out += ["          HealthCheck:", f"            Command: {json.dumps(['CMD', *check])}",
                "            Interval: 30", "            Timeout: 5", "            Retries: 3",
                "            StartPeriod: 20"]
    out += ["", "  Service:", "    Type: AWS::ECS::Service", "    DependsOn: PublicRoute"]
    out += [
        "    Properties:",
        "      Cluster: !Ref Cluster",
        "      TaskDefinition: !Ref TaskDefinition",
        "      LaunchType: FARGATE",
        "      DesiredCount: !If [HasImage, 1, 0]  # no tasks until the workflow has pushed an image",
        "      NetworkConfiguration:",
        "        AwsvpcConfiguration:",
        "          AssignPublicIp: ENABLED",
        "          Subnets: [!Ref SubnetA, !Ref SubnetB]",
        "          SecurityGroups: [!Ref ServiceSecurityGroup]",
        "      DeploymentConfiguration:",
        "        DeploymentCircuitBreaker:  # a version that doesn't start is rolled back",
        "          Enable: true",
        "          Rollback: true",
    ]
    return out


# ---------------------------------------------------------------- workflow

def _workflow(ecs: bool, region: str, v: dict) -> str:
    steps = [
        step("Check out the code", uses=pins.pin("actions/checkout", v)),
        _aws_login(v),
        step("Sign in to Amazon ECR", uses=pins.pin("aws-actions/amazon-ecr-login", v)),
        step("Find the repository", id="stack", run="\n".join([
            'uri=$(aws cloudformation describe-stacks --stack-name "$STACK_NAME" \\',
            "  --query \"Stacks[0].Outputs[?OutputKey=='RepositoryUri'].OutputValue\" --output text)",
            'echo "repository=$uri" >> "$GITHUB_OUTPUT"'])),
        step("Set up arm64 emulation", uses=pins.pin("docker/setup-qemu-action", v)),
        step("Set up Docker Buildx", uses=pins.pin("docker/setup-buildx-action", v)),
        step("Build and push the image", uses=pins.pin("docker/build-push-action", v), with_={
            "context": ".", "platforms": "linux/arm64", "push": True,
            "tags": "${{ steps.stack.outputs.repository }}:${{ github.sha }}",
            "cache-from": "type=gha", "cache-to": "type=gha,mode=max"}),
    ]
    if ecs:
        steps.append(step("Roll out the new image", run="\n".join([
            'aws cloudformation update-stack --stack-name "$STACK_NAME" --use-previous-template \\',
            "  --capabilities CAPABILITY_IAM \\",
            '  --parameters ParameterKey=ImageTag,ParameterValue="$GITHUB_SHA" \\',
            "               ParameterKey=GitHubRepository,UsePreviousValue=true",
            "# Waits until the new task is healthy; a version that doesn't start is rolled back.",
            'aws cloudformation wait stack-update-complete --stack-name "$STACK_NAME"'])))
    what = "builds the image, pushes it to ECR and rolls it out to ECS" if ecs else "builds the image and pushes it to ECR"
    return "\n".join([
        f"# Generated by InfraPilot: {what} on each push.",
        "name: Deploy container",
        "",
        "on:",
        "  push:",
        "    branches: [main]",
        "  workflow_dispatch:  # also lets you run it by hand from the Actions tab",
        "",
        "permissions:",
        "  contents: read",
        "",
        "# One deploy at a time; a newer push waits instead of cancelling a rollout halfway.",
        "concurrency:",
        "  group: deploy-container",
        "  cancel-in-progress: false",
        "",
        "env:",
        f"  AWS_REGION: {region}",
        f"  STACK_NAME: {STACK}",
        "",
        "jobs:",
        "  deploy:",
        "    runs-on: ubuntu-latest",
        "    timeout-minutes: 30",
        "    environment: production",
        "    permissions:",
        "      contents: read",
        "      id-token: write  # lets the job sign in to AWS with OIDC (no stored AWS keys)",
        "    steps:",
        "\n".join(_indent(s, 6) for s in steps),
    ]) + "\n"


